export async function prepareDemo(root, stage) {
  await mkdir(stage, { recursive: true });
  for (const file of demoFiles) {
    await mkdir(resolve(stage, file, ".."), { recursive: true });
    await cp(join(root, file), join(stage, file));
  }
  await writeFile(
    join(stage, "src/app/page.tsx"),
    'import { HotelHome } from "@/features/hotel/home";\nexport default function Home() { return <HotelHome />; }\n',
  );
  await writeFile(
    join(stage, "src/components/inquiry-form.tsx"),
    'export { InquiryForm } from "@/features/inquiries/demo/guest-inquiry-form";\n',
  );
  await writeFile(
    join(stage, "next.config.ts"),
    `import type { NextConfig } from "next";\nconst config: NextConfig = { output: "export", trailingSlash: true, images: { unoptimized: true }, poweredByHeader: false, reactStrictMode: true, turbopack: { root: ${JSON.stringify(root)} } };\nexport default config;\n`,
  );
  const { compilerOptions } = JSON.parse(
    await readFile(join(root, "tsconfig.json"), "utf8"),
  );
  await writeFile(
    join(stage, "tsconfig.json"),
    JSON.stringify(
      {
        compilerOptions,
        include: [
          "next-env.d.ts",
          "src/**/*.ts",
          "src/**/*.tsx",
          ".next/types/**/*.ts",
        ],
        exclude: ["node_modules"],
      },
      null,
      2,
    ),
  );
  await cp(join(root, "postcss.config.mjs"), join(stage, "postcss.config.mjs"));
  const { dependencies, devDependencies } = JSON.parse(
    await readFile(join(root, "package.json"), "utf8"),
  );
  await writeFile(
    join(stage, "package.json"),
    JSON.stringify({
      name: "aster-public-showcase",
      private: true,
      dependencies,
      devDependencies,
    }),
  );
  await symlink(
    join(root, "node_modules"),
    join(stage, "node_modules"),
    process.platform === "win32" ? "junction" : "dir",
  );
}

export async function buildDemo(
  root = fileURLToPath(new URL("../", import.meta.url)),
) {
  const stage = join(root, ".demo-build");
  const marker = join(stage, ".aster-generated-stage");
  try {
    await access(stage);
    await access(marker);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    try {
      await access(stage);
      throw new Error(
        "Refusing to overwrite an unrecognized .demo-build directory",
      );
    } catch (check) {
      if (check.code !== "ENOENT") throw check;
    }
  }
  await rm(stage, { recursive: true, force: true });
  // Clear old publish output so a failed build cannot leave a stale deployable site.
  await rm(join(root, "out"), { recursive: true, force: true });
  await mkdir(stage, { recursive: true });
  await writeFile(marker, "Generated by npm run build:demo\n");
  await prepareDemo(root, stage);
  const env = {};
  for (const key of [
    "PATH",
    "Path",
    "HOME",
    "USERPROFILE",
    "SystemRoot",
    "SYSTEMROOT",
    "WINDIR",
    "TEMP",
    "TMP",
    "TMPDIR",
    "COMSPEC",
    "ComSpec",
    "PATHEXT",
    "LOCALAPPDATA",
    "NUMBER_OF_PROCESSORS",
  ]) {
    if (process.env[key] !== undefined) env[key] = process.env[key];
  }
  env.NODE_ENV = "production";
  env.NEXT_TELEMETRY_DISABLED = "1";
  const require = createRequire(import.meta.url);
  const result = spawnSync(
    process.execPath,
    [require.resolve("next/dist/bin/next"), "build"],
    { cwd: stage, env, stdio: "inherit" },
  );
  if (result.error) throw result.error;
  if (result.status !== 0)
    throw new Error(`Static build failed (${result.status ?? result.signal})`);
  const exported = join(stage, "out");
  await writeFile(
    join(exported, "_headers"),
    `/*\n  X-Content-Type-Options: nosniff\n  X-Frame-Options: DENY\n  Referrer-Policy: strict-origin-when-cross-origin\n  Permissions-Policy: camera=(), microphone=(), geolocation=()\n  Content-Security-Policy: default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self'; font-src 'self'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'none'\n`,
  );
  await verifyDemoOutput(exported);
  await cp(exported, join(root, "out"), { recursive: true });
  console.log(
    "Static showcase verified. Publish only out/; never publish the checkout or .demo-build/.",
  );
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await buildDemo();
}
